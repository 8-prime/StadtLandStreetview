#!/usr/bin/env python3
"""Generate backend/data/start-points.csv: random search starts per country.

Usage (from the repository root):

    python3 -I scripts/start_points.py                 # unverified town centres
    SLS_STREETVIEW_KEY=... python3 -I scripts/start_points.py --verify

Towns come from GeoNames `cities15000` (CC BY 4.0, https://www.geonames.org/).
Only countries in COVERED below are used. `--verify` asks the Street View Static
API *metadata* endpoint (free of charge, but needs a key that allows that API) for
the nearest outdoor panorama, drops towns without one, and stores the panorama's
exact location. The game itself never makes these requests: the backend only reads
the generated file. Unverified starts still work because the browser looks for the
nearest panorama within a few kilometres when a search begins.
"""

import argparse
import csv
import io
import json
import os
import sys
import time
import urllib.parse
import urllib.request
import zipfile
from collections import defaultdict
from pathlib import Path

SOURCE = "https://download.geonames.org/export/dump/cities15000.zip"
METADATA = "https://maps.googleapis.com/maps/api/streetview/metadata"
OUTPUT = Path(__file__).resolve().parent.parent / "backend" / "data" / "start-points.csv"

# Countries with broad official Street View coverage. Verification removes misses.
COVERED = set("""
AD AL AT BE BG CH CZ DE DK EE ES FI FO FR GB GI GR HR HU IE IM IS IT JE LI LT LU
LV MC ME MK MT NL NO PL PT RO RS RU SE SI SK SM TR UA
US CA MX GT CO EC PE BO CL AR UY BR DO PR
JP KR TW HK MO TH MY SG ID PH KH LA BD LK IN BT MN KZ KG IL JO AE QA
ZA BW LS SZ KE UG RW NG GH SN TN
AU NZ
""".split())


def towns():
    with urllib.request.urlopen(SOURCE, timeout=120) as response:
        archive = zipfile.ZipFile(io.BytesIO(response.read()))
    with archive.open("cities15000.txt") as raw:
        for row in csv.reader(io.TextIOWrapper(raw, "utf-8"), delimiter="\t", quoting=csv.QUOTE_NONE):
            if row[8] in COVERED and row[6] == "P":
                yield row[8], float(row[4]), float(row[5]), int(row[14] or 0)


def nearest_panorama(key, lat, lng, radius):
    query = urllib.parse.urlencode({
        "location": f"{lat},{lng}", "radius": radius, "source": "outdoor", "key": key,
    })
    with urllib.request.urlopen(f"{METADATA}?{query}", timeout=30) as response:
        result = json.load(response)
    if result.get("status") == "OK":
        return result["location"]["lat"], result["location"]["lng"]
    if result.get("status") not in ("ZERO_RESULTS", "NOT_FOUND"):
        sys.exit(f"Metadata request failed: {result.get('status')} {result.get('error_message', '')}")
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--per-country", type=int, default=25, help="largest towns kept per country")
    parser.add_argument("--verify", action="store_true", help="snap to panoramas with SLS_STREETVIEW_KEY")
    parser.add_argument("--radius", type=int, default=1000, help="verification search radius in metres")
    args = parser.parse_args()
    key = os.environ.get("SLS_STREETVIEW_KEY", "").strip()
    if args.verify and not key:
        sys.exit("Set SLS_STREETVIEW_KEY to verify panoramas.")

    by_country = defaultdict(list)
    for country, lat, lng, population in towns():
        by_country[country].append((population, lat, lng))

    rows = []
    for country in sorted(by_country):
        kept = 0
        for _, lat, lng in sorted(by_country[country], reverse=True):
            if kept >= args.per_country:
                break
            if args.verify:
                found = nearest_panorama(key, lat, lng, args.radius)
                time.sleep(0.02)
                if not found:
                    continue
                lat, lng = found
            rows.append(f"{country},{lat:.5f},{lng:.5f}")
            kept += 1
        print(f"{country}: {kept}", file=sys.stderr)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    header = [
        "# Search start points: country,lat,lng. Generated by scripts/start_points.py.",
        "# Town data: GeoNames (https://www.geonames.org/), CC BY 4.0.",
        f"# Panoramas verified: {'yes' if args.verify else 'no'}.",
    ]
    OUTPUT.write_text("\n".join(header + rows) + "\n")
    print(f"Wrote {len(rows)} points for {len({r[:2] for r in rows})} countries to {OUTPUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
