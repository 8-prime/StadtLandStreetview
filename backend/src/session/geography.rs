//! Offline geography: country lookup for banned countries and random search starts.
//! Nothing here calls Google; both datasets are compiled into the executable.

use std::{
    collections::{BTreeMap, HashSet},
    sync::LazyLock,
};

use country_boundaries::{BOUNDARIES_ODBL_180X90, CountryBoundaries, LatLon};

use super::{Position, Result, SessionError};

/// The most countries a room can ban. There are fewer ISO 3166-1 codes than this.
pub const MAX_BANNED_COUNTRIES: usize = 250;

// Country boundaries © OpenStreetMap contributors, ODbL.
static BOUNDARIES: LazyLock<CountryBoundaries> = LazyLock::new(|| {
    CountryBoundaries::from_reader(BOUNDARIES_ODBL_180X90).expect("bundled boundaries are valid")
});

/// Town centres per ISO country code. Generated by `scripts/start_points.py`.
static START_POINTS: LazyLock<BTreeMap<&'static str, Vec<Position>>> = LazyLock::new(|| {
    let mut points: BTreeMap<_, Vec<_>> = BTreeMap::new();
    for line in include_str!("../../data/start-points.csv").lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let mut fields = line.split(',');
        let (Some(country), Some(lat), Some(lng)) = (fields.next(), fields.next(), fields.next())
        else {
            panic!("malformed start point: {line}");
        };
        let position = Position {
            lat: lat.parse().expect("start point latitude"),
            lng: lng.parse().expect("start point longitude"),
        };
        points.entry(country).or_default().push(position);
    }
    points
});

/// Normalizes ISO 3166-1 alpha-2 codes to sorted, unique upper case.
pub(super) fn normalize_countries(codes: &[String]) -> Result<Vec<String>> {
    let mut normalized = codes
        .iter()
        .map(|code| code.trim().to_ascii_uppercase())
        .collect::<Vec<_>>();
    if normalized
        .iter()
        .any(|code| code.len() != 2 || !code.bytes().all(|byte| byte.is_ascii_uppercase()))
    {
        return Err(SessionError::InvalidInput(
            "Banned countries must be two-letter ISO country codes.",
        ));
    }
    normalized.sort_unstable();
    normalized.dedup();
    if normalized.len() > MAX_BANNED_COUNTRIES {
        return Err(SessionError::InvalidInput("Too many banned countries."));
    }
    if START_POINTS.keys().all(|country| {
        normalized
            .binary_search_by(|code| code.as_str().cmp(*country))
            .is_ok()
    }) {
        return Err(SessionError::InvalidInput(
            "Leave at least one country with Street View open.",
        ));
    }
    Ok(normalized)
}

/// The first banned country containing `position`, if any. Only reliable on land,
/// which is where Street View panoramas are.
pub(super) fn banned_country(position: Position, banned: &[String]) -> Option<String> {
    if banned.is_empty() {
        return None;
    }
    let location = LatLon::new(position.lat, position.lng).ok()?;
    BOUNDARIES
        .ids(location)
        .into_iter()
        .find(|id| banned.iter().any(|code| code == id))
        .map(str::to_owned)
}

/// One start per player. Countries are drawn uniformly so large countries do not
/// dominate, and no country repeats until every allowed country has been used.
pub(super) fn random_starts(
    count: usize,
    banned: &[String],
    rng: &mut fastrand::Rng,
) -> Vec<Position> {
    let allowed_by_boundaries = |position: &&Position| banned_country(**position, banned).is_none();
    let pool = START_POINTS
        .iter()
        .filter(|(country, _)| !banned.iter().any(|code| code == *country))
        .map(|(_, points)| {
            points
                .iter()
                .filter(allowed_by_boundaries)
                .collect::<Vec<_>>()
        })
        .filter(|points| !points.is_empty())
        .collect::<Vec<_>>();
    if pool.is_empty() {
        return Vec::new();
    }
    let mut used = HashSet::new();
    let mut countries = Vec::new();
    (0..count)
        .map(|_| {
            if countries.is_empty() {
                countries = (0..pool.len()).collect();
                rng.shuffle(&mut countries);
            }
            let points = &pool[countries.pop().unwrap()];
            // Points are distinct within a country; avoid sharing one when possible.
            let mut position = *points[rng.usize(..points.len())];
            for _ in 0..points.len() {
                if used.insert(position_key(position)) {
                    break;
                }
                position = *points[rng.usize(..points.len())];
            }
            position
        })
        .collect()
}

fn position_key(position: Position) -> (u64, u64) {
    (position.lat.to_bits(), position.lng.to_bits())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn codes(values: &[&str]) -> Vec<String> {
        values.iter().map(|code| (*code).to_owned()).collect()
    }

    #[test]
    fn start_points_lie_in_their_own_country() {
        let mut misplaced = Vec::new();
        for (country, points) in START_POINTS.iter() {
            for point in points {
                let location = LatLon::new(point.lat, point.lng).unwrap();
                if !BOUNDARIES.is_in(location, country) {
                    misplaced.push(format!("{country} {point:?}"));
                }
            }
        }
        // A handful of coastal towns can sit just outside simplified land borders.
        assert!(
            misplaced.len() * 50 < START_POINTS.values().map(Vec::len).sum(),
            "{misplaced:?}"
        );
    }

    #[test]
    fn country_lookup_uses_iso_codes_and_subdivisions() {
        let berlin = Position {
            lat: 52.52,
            lng: 13.405,
        };
        let dallas = Position {
            lat: 32.78,
            lng: -96.80,
        };
        assert_eq!(banned_country(berlin, &codes(&["DE"])), Some("DE".into()));
        assert_eq!(banned_country(berlin, &codes(&["AT", "FR"])), None);
        assert_eq!(banned_country(dallas, &codes(&["US"])), Some("US".into()));
        assert_eq!(banned_country(berlin, &[]), None);
    }

    #[test]
    fn normalization_sorts_dedupes_and_rejects_bad_codes() {
        assert_eq!(
            normalize_countries(&codes(&[" de", "FR", "DE"])).unwrap(),
            codes(&["DE", "FR"])
        );
        assert!(normalize_countries(&codes(&["DEU"])).is_err());
        assert!(normalize_countries(&codes(&["1A"])).is_err());
        let everything = START_POINTS
            .keys()
            .map(|code| (*code).to_owned())
            .collect::<Vec<_>>();
        assert!(normalize_countries(&everything).is_err());
        assert!(normalize_countries(&everything[1..]).is_ok());
    }

    #[test]
    fn starts_avoid_banned_countries_and_spread_across_countries() {
        let mut rng = fastrand::Rng::with_seed(7);
        let allowed = START_POINTS
            .keys()
            .take(3)
            .map(|code| (*code).to_owned())
            .collect::<Vec<_>>();
        let banned = START_POINTS
            .keys()
            .skip(3)
            .map(|code| (*code).to_owned())
            .collect::<Vec<_>>();
        let starts = random_starts(3, &banned, &mut rng);
        assert_eq!(starts.len(), 3);
        let mut countries = starts
            .iter()
            .map(|start| {
                allowed
                    .iter()
                    .find(|code| START_POINTS[code.as_str()].contains(start))
                    .unwrap()
            })
            .collect::<Vec<_>>();
        countries.sort();
        countries.dedup();
        assert_eq!(
            countries.len(),
            3,
            "each player starts in a different country"
        );
        // More players than countries still get a start each.
        assert_eq!(random_starts(12, &banned, &mut rng).len(), 12);
    }
}
